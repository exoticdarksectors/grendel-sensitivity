# =========================================================================
# Geometry: ray-cast through the GRENDEL mesh (lazy import)
# =========================================================================

def _get_mesh():
    """Lazy-import the GRENDEL mesh from the shared ``higgs/`` single source."""
    if not RECO_DIR.exists():
        raise FileNotFoundError(
            f"higgs/ directory not found at {RECO_DIR}.\n"
            "The checkout is incomplete; higgs/grendel_geometry.py is required."
        )
    if str(RECO_DIR) not in sys.path:
        sys.path.insert(0, str(RECO_DIR))
    from grendel_geometry import mesh_fiducial
    return mesh_fiducial


def _eta_phi_to_directions_batch(eta, phi):
    """(eta, phi) arrays -> (N, 3) unit direction vectors."""
    theta = 2.0 * np.arctan(np.exp(-eta))
    dx = np.sin(theta) * np.cos(phi)
    dy = np.sin(theta) * np.sin(phi)
    dz = np.cos(theta)
    return np.column_stack([dx, dy, dz])


def compute_geometry(eta, phi, mesh, origin=CMS_ORIGIN, batch_label=""):
    """Batch ray-cast (eta, phi) directions against the GRENDEL mesh."""
    n = len(eta)
    origin_arr = np.array(origin, dtype=np.float64)
    hits = np.zeros(n, dtype=bool)
    entry_d = np.full(n, np.nan)
    exit_d = np.full(n, np.nan)

    directions = _eta_phi_to_directions_batch(eta, phi)
    candidates = np.where(directions[:, 1] > 0.01)[0]
    n_cand = len(candidates)
    if n_cand == 0:
        return hits, entry_d, exit_d

    print(f"  Batch ray-casting {n_cand}/{n} candidates {batch_label}...",
          flush=True)

    cand_dirs = directions[candidates]
    # Chunk the ray-cast: intersects_location allocates per-ray x per-triangle
    # intermediates, so casting all candidates at once spikes to several GB on
    # the highest-multiplicity (lowest-mass) points. Rays are independent, so
    # batching gives identical results while bounding peak memory.
    GEOM_RAY_CHUNK = 25000
    loc_parts, rid_parts = [], []
    for cs in range(0, n_cand, GEOM_RAY_CHUNK):
        ce = min(cs + GEOM_RAY_CHUNK, n_cand)
        chunk_dirs = cand_dirs[cs:ce]
        chunk_origins = np.tile(origin_arr, (len(chunk_dirs), 1))
        loc_c, rid_c, _ = mesh.ray.intersects_location(
            ray_origins=chunk_origins, ray_directions=chunk_dirs)
        if len(loc_c):
            loc_parts.append(loc_c)
            rid_parts.append(rid_c + cs)  # ray_ids are chunk-local; shift to candidate index

    if not loc_parts:
        print(f"  0/{n} events hit detector", flush=True)
        return hits, entry_d, exit_d
    locations = np.concatenate(loc_parts)
    ray_ids = np.concatenate(rid_parts)

    dists = np.linalg.norm(locations - origin_arr, axis=1)
    order = np.argsort(ray_ids)
    sorted_ray_ids = ray_ids[order]
    sorted_dists = dists[order]

    unique_rays, start_idx, counts = np.unique(
        sorted_ray_ids, return_index=True, return_counts=True)

    valid = counts >= 2
    valid_rays = unique_rays[valid]
    valid_starts = start_idx[valid]
    valid_counts = counts[valid]

    for i in range(len(valid_rays)):
        ray_local = valid_rays[i]
        orig_idx = candidates[ray_local]
        s = valid_starts[i]
        e = s + valid_counts[i]
        ray_dists = sorted_dists[s:e]
        ray_dists.sort()
        hits[orig_idx] = True
        entry_d[orig_idx] = ray_dists[0]
        exit_d[orig_idx] = ray_dists[1]

    n_hits = int(hits.sum())
    print(f"  {n_hits}/{n} events hit detector ({n_hits / n * 100:.2f}%)",
          flush=True)
    if n_hits > 0:
        path_lens = exit_d[hits] - entry_d[hits]
        print(f"  Mean path length: {path_lens.mean():.2f} m", flush=True)
    return hits, entry_d, exit_d


def load_or_compute_geometry(flavor, mass_label, eta, phi, mesh, force=False,
                             source_mtime=None):
    """Load cached geometry or compute + cache as NPZ.

    The cache is keyed on (flavor, mass) only, so a stale NPZ is invalidated
    whenever the source 4-vector CSV is newer than the cache (``source_mtime``):
    regenerating a combined CSV forces a fresh ray-cast instead of serving old
    hits. Geometry-code changes are not tracked by mtime -- pass --force-geometry
    after editing the GRENDEL mesh.
    """
    cache_dir = GEOM_CACHE_DIR / flavor
    cache_path = cache_dir / f"geom_{mass_label}.npz"

    fresh = cache_path.exists() and not force
    if fresh and source_mtime is not None:
        fresh = cache_path.stat().st_mtime >= source_mtime
    if fresh:
        data = np.load(cache_path)
        return data["hits"].astype(bool), data["entry_d"], data["exit_d"]

    hits, entry_d, exit_d = compute_geometry(
        eta, phi, mesh, CMS_ORIGIN, batch_label=f"[{flavor}/{mass_label}]")

    cache_dir.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(cache_path, hits=hits, entry_d=entry_d, exit_d=exit_d)
    return hits, entry_d, exit_d


# =========================================================================
# FairShip decay templates
# =========================================================================

def load_decay_templates(flavor, mass_label):
    """Cached rest-frame decay templates for (flavor, mass), or None if absent."""
    path = TEMPLATE_DIR / flavor / f"templates_{mass_label}.npz"
    if not path.exists():
        return None
    return np.load(path)


def _seed_for(flavor, mass_label):
    """Deterministic per-point RNG seed (order-independent, reproducible)."""
    h = hashlib.md5(f"{flavor}/{mass_label}".encode()).digest()
    return int.from_bytes(h[:4], "little")


# =========================================================================
# Single-point processing
# =========================================================================

def _select_hit_sample(idx, weights, max_hit_events, rng):
    """Return hit indices and scan weights for exact or approximate evaluation."""
    weights = np.asarray(weights, dtype=float)
    if max_hit_events is None or max_hit_events <= 0 or len(idx) <= max_hit_events:
        return idx, weights, "exact"

    total_weight = float(weights.sum())
    if total_weight > 0.0 and np.isfinite(total_weight):
        probabilities = weights / total_weight
        sampled_idx = rng.choice(
            idx, size=int(max_hit_events), replace=True, p=probabilities)
        sampled_weights = np.full(
            len(sampled_idx), total_weight / len(sampled_idx), dtype=float)
        return sampled_idx, sampled_weights, "weighted_resample"

    sampled_pos = rng.choice(len(idx), size=int(max_hit_events), replace=False)
    sampled_idx = idx[sampled_pos]
    sampled_weights = np.asarray(weights[sampled_pos], dtype=float)
    sampled_weights *= len(idx) / max(len(sampled_idx), 1)
    return sampled_idx, sampled_weights, "uniform_rescale"


def process_mass_point(flavor, mass, mesh,
                       force_geometry=False, save_diagnostic=False,
                       decay_samples=DECAY_SAMPLES, max_hit_events=None):
    """Process one (flavor, mass) point and return its exclusion band."""
    mass_label = format_mass_for_filename(mass)
    csv_path = LLP_VECTORS_DIR / flavor / "combined" / f"mN_{mass_label}.csv"

    if not csv_path.exists() or csv_path.stat().st_size == 0:
        return None

    data = load_combined_csv(csv_path, mass)
    n_events = len(data["weight"])
    if n_events == 0:
        return None

    hits, entry_d, exit_d = load_or_compute_geometry(
        flavor, mass_label, data["eta"], data["phi"], mesh,
        force=force_geometry, source_mtime=csv_path.stat().st_mtime)

    n_hits = int(hits.sum())
    if n_hits == 0:
        return {
            "mass_GeV": mass, "flavor": flavor,
            "u2_min": np.nan, "u2_max": np.nan,
            "u2_min_open": False, "u2_max_open": False,
            "peak_N": 0.0, "peak_u2": np.nan,
            "has_sensitivity": False, "n_events": n_events, "n_hits": 0,
        }

    templates = load_decay_templates(flavor, mass_label)
    if templates is None:
        print(f"  NOTE: no decay templates for {flavor}/{mass_label}; "
              "run generate_decay_templates.py first. Skipping.")
        return None
    ctau_u2_1 = float(templates["ctau_m_u2eq1"])
    if ctau_u2_1 <= 0:
        return None

    # Build the acceptance MC for the hitting events only.
    idx_all = np.where(hits & np.isfinite(entry_d) & np.isfinite(exit_d))[0]
    rng = np.random.default_rng(_seed_for(flavor, mass_label))
    idx, scan_weights, hit_estimator = _select_hit_sample(
        idx_all, data["weight"][idx_all], max_hit_events, rng)
    direction = _eta_phi_to_directions_batch(data["eta"][idx], data["phi"][idx])
    p_mag = data["beta_gamma"][idx] * mass
    energy = data["gamma"][idx] * mass
    p4 = np.column_stack([energy, p_mag[:, None] * direction])
    d, passed = build_event_mc(
        p4, direction, entry_d[idx], exit_d[idx], templates, decay_samples,
        rng, origin=CMS_ORIGIN)

    u2_grid = np.logspace(LOG_U2_MIN, LOG_U2_MAX, N_U2_POINTS)
    u2_grid, N_grid = scan_u2(
        d, passed, exit_d[idx] - entry_d[idx], scan_weights,
        data["beta_gamma"][idx], ctau_u2_1, L_INT_PB, u2_grid)

    result = find_exclusion_band(u2_grid, N_grid, N_THRESHOLD)
    result["mass_GeV"] = mass
    result["flavor"] = flavor
    result["n_events"] = n_events
    result["n_hits"] = n_hits
    result["n_hits_eval"] = len(idx)
    result["decay_samples"] = decay_samples
    result["hit_estimator"] = hit_estimator

    if save_diagnostic:
        diag_dir = ANALYSIS_DIR / "diagnostics"
        plot_nsignal_vs_u2(u2_grid, N_grid, mass, flavor, diag_dir)

    return result


# =========================================================================
# Parallel worker plumbing
# =========================================================================

_WORKER_MESH = None


def _worker_init():
    global _WORKER_MESH
    _WORKER_MESH = _get_mesh()


def _worker_process_point(args):
    flavor, mass, force_geom, save_diag, decay_samples, max_hit_events = args
    t0 = time.time()
    result = process_mass_point(
        flavor, mass, _WORKER_MESH,
        force_geometry=force_geom, save_diagnostic=save_diag,
        decay_samples=decay_samples, max_hit_events=max_hit_events)
    elapsed = time.time() - t0
    mass_label = format_mass_for_filename(mass)
    tag = f"{flavor}/mN_{mass_label}"
    if result and result.get("has_sensitivity"):
        print(f"  {tag}: sensitivity found ({elapsed:.1f}s)", flush=True)
    elif result:
        print(f"  {tag}: done, no sensitivity ({elapsed:.1f}s)", flush=True)
    else:
        print(f"  {tag}: skipped ({elapsed:.1f}s)", flush=True)
    return result


# =========================================================================
# Driver
# =========================================================================

def run(flavors, masses, n_workers=1, force_geometry=False,
        save_diagnostics=False, decay_samples=DECAY_SAMPLES,
        max_hit_events=None, checkpoint_every=0):
    ANALYSIS_DIR.mkdir(parents=True, exist_ok=True)
    GEOM_CACHE_DIR.mkdir(parents=True, exist_ok=True)

    work_items = []
    for flavor in flavors:
        for mass in masses:
            work_items.append((
                flavor, mass, force_geometry, save_diagnostics,
                decay_samples, max_hit_events))

    n_total = len(work_items)
    print(f"\nProcessing {n_total} mass points "
          f"with {n_workers} worker(s)...\n", flush=True)

    t_start = time.time()
    results = []
    status_path = ANALYSIS_DIR / "scan_status.json"
    partial_csv = ANALYSIS_DIR / "hnl_sensitivity.partial.csv"

    def _write_partial(done):
        if not results:
            return
        rows = sorted(results, key=lambda r: (r["flavor"], r["mass_GeV"]))
        pd.DataFrame(rows).to_csv(partial_csv, index=False)
        if checkpoint_every and done % checkpoint_every == 0:
            plot_exclusion(partial_csv, ANALYSIS_DIR,
                           basename="hnl_exclusion_partial")

    def _write_status(done, n_sens):
        elapsed = time.time() - t_start
        eta = (elapsed / max(done, 1)) * (n_total - done) if done > 0 else 0
        status = {
            "ts": datetime.now().isoformat(),
            "done": done, "total": n_total,
            "n_sensitive": n_sens,
            "elapsed_s": round(elapsed, 1),
            "eta_s": round(eta, 1),
        }
        status_path.write_text(json.dumps(status, indent=2))

    if n_workers <= 1:
        mesh = _get_mesh()
        for i, item in enumerate(work_items):
            flavor, mass, fg, sd, ds, mhe = item
            t0 = time.time()
            r = process_mass_point(flavor, mass, mesh,
                                   force_geometry=fg, save_diagnostic=sd,
                                   decay_samples=ds, max_hit_events=mhe)
            elapsed = time.time() - t0
            mass_label = format_mass_for_filename(mass)
            if r is not None:
                results.append(r)
                _write_partial(i + 1)
            n_sens = sum(1 for r in results if r.get("has_sensitivity"))
            _write_status(i + 1, n_sens)
            print(f"  [{i+1}/{n_total}] {flavor}/mN_{mass_label} "
                  f"({elapsed:.1f}s)", flush=True)
    else:
        with ProcessPoolExecutor(
            max_workers=n_workers, initializer=_worker_init
        ) as pool:
            futures = {
                pool.submit(_worker_process_point, item): i
                for i, item in enumerate(work_items)
            }
            done_count = 0
            for future in as_completed(futures):
                done_count += 1
                r = future.result()
                if r is not None:
                    results.append(r)
                    _write_partial(done_count)
                n_sens = sum(1 for r in results if r.get("has_sensitivity"))
                _write_status(done_count, n_sens)
                if done_count % 10 == 0 or done_count == n_total:
                    elapsed = time.time() - t_start
                    print(f"  [{done_count}/{n_total}] "
                          f"{n_sens} sensitive, "
                          f"{elapsed:.0f}s elapsed", flush=True)

    total_time = time.time() - t_start

    # Honest coverage accounting: every requested (flavor, mass) that produced
    # no result is recorded with the reason it was dropped, so a missing point
    # never silently disappears from the money plot.
    processed = {(r["flavor"], r["mass_GeV"]) for r in results}
    skipped = []
    for flavor in flavors:
        for mass in masses:
            if (flavor, mass) in processed:
                continue
            label = format_mass_for_filename(mass)
            csv = LLP_VECTORS_DIR / flavor / "combined" / f"mN_{label}.csv"
            tmpl = TEMPLATE_DIR / flavor / f"templates_{label}.npz"
            if not csv.exists() or csv.stat().st_size == 0:
                reason = "missing_or_empty_combined_csv"
            elif not tmpl.exists():
                reason = "missing_decay_templates"
            else:
                reason = "no_acceptance_or_nonpositive_ctau"
            skipped.append({"flavor": flavor, "mass_GeV": mass, "reason": reason})

    n_requested = len(flavors) * len(masses)
    n_processed = len(results)
    meta = {
        "timestamp": datetime.now().isoformat(),
        "flavors": flavors,
        "n_masses": len(masses),
        "n_points_requested": n_requested,
        "n_points_processed": n_processed,
        "n_points_skipped": len(skipped),
        "skipped": skipped,
        "n_workers": n_workers,
        "decay_samples": decay_samples,
        "max_hit_events": max_hit_events,
        "checkpoint_every": checkpoint_every,
        "n_results": n_processed,
        "n_sensitive": 0,
        "mass_range": [float(min(masses)), float(max(masses))],
        "total_time_s": round(total_time, 1),
        "llp_vectors_dir": str(LLP_VECTORS_DIR),
    }

    if skipped:
        by_reason = {}
        for s in skipped:
            by_reason[s["reason"]] = by_reason.get(s["reason"], 0) + 1
        print(f"\nWARNING: {len(skipped)}/{n_requested} requested points "
              f"skipped (recorded in run_metadata.json):")
        for reason, n in sorted(by_reason.items()):
            print(f"    {n:4d}  {reason}")

    if not results:
        print("\nNo results produced -- every requested point was skipped.")
        (ANALYSIS_DIR / "run_metadata.json").write_text(json.dumps(meta, indent=2))
        return 0

    results.sort(key=lambda r: (r["flavor"], r["mass_GeV"]))
    df = pd.DataFrame(results)
    out_csv = ANALYSIS_DIR / "hnl_sensitivity.csv"
    df.to_csv(out_csv, index=False)
    print(f"\nResults saved: {out_csv}")

    n_sens = int(df["has_sensitivity"].sum())
    meta["n_sensitive"] = n_sens
    print(f"Sensitivity found at {n_sens}/{len(df)} mass points")
    print(f"Total time: {total_time:.0f}s ({total_time/60:.1f} min)")

    (ANALYSIS_DIR / "run_metadata.json").write_text(json.dumps(meta, indent=2))

    plot_exclusion(out_csv, ANALYSIS_DIR)
    return n_processed


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="HNL sensitivity + (m_N, U^2) money plot")
    parser.add_argument(
        "--flavor", nargs="+", default=None, choices=FLAVORS,
        help=f"Flavors to process (default: {DEFAULT_FLAVORS})")
    parser.add_argument(
        "--mass", nargs="+", type=float, default=None,
        help=f"Specific masses in GeV (default: full grid <= {ANALYSIS_MASS_MAX} GeV)")
    parser.add_argument(
        "--plot-only", action="store_true",
        help="Re-plot from existing results CSV")
    parser.add_argument(
        "--force-geometry", action="store_true",
        help="Recompute geometry cache (ignore existing NPZ)")
    parser.add_argument(
        "--diagnostics", action="store_true",
        help="Save N_signal vs U^2 plots for each mass point")
    parser.add_argument(
        "--workers", type=int, default=3,
        help="Number of parallel workers (default: 3)")
    parser.add_argument(
        "--decay-samples", type=int, default=DECAY_SAMPLES,
        help=f"Decay positions sampled per hit event (default: {DECAY_SAMPLES})")
    parser.add_argument(
        "--max-hit-events", type=int, default=None,
        help="Approximate mode: weighted-resample at most this many hit events per mass point")
    parser.add_argument(
        "--mass-stride", type=int, default=1,
        help="Approximate mode: keep every Nth mass-grid point (default: 1)")
    parser.add_argument(
        "--mass-offset", type=int, default=0,
        help="Approximate mode: offset used with --mass-stride (default: 0)")
    parser.add_argument(
        "--checkpoint-every", type=int, default=0,
        help="Write partial CSV always; additionally plot partial result every N completed points")
    args = parser.parse_args(argv)

    if args.decay_samples < 1:
        parser.error("--decay-samples must be >= 1")
    if args.max_hit_events is not None and args.max_hit_events < 1:
        parser.error("--max-hit-events must be >= 1 when provided")
    if args.mass_stride < 1:
        parser.error("--mass-stride must be >= 1")
    if args.mass_offset < 0 or args.mass_offset >= args.mass_stride:
        parser.error("--mass-offset must satisfy 0 <= offset < stride")
    if args.checkpoint_every < 0:
        parser.error("--checkpoint-every must be >= 0")

    if args.plot_only:
        csv_path = ANALYSIS_DIR / "hnl_sensitivity.csv"
        if not csv_path.exists():
            print(f"No results file found: {csv_path}")
            return 1
        plot_exclusion(csv_path, ANALYSIS_DIR)
        return 0

    flavors = args.flavor or DEFAULT_FLAVORS
    masses = args.mass or [m for m in MASS_GRID if m <= ANALYSIS_MASS_MAX]
    if args.mass_stride > 1:
        masses = masses[args.mass_offset::args.mass_stride]
    if not masses:
        parser.error("selected mass grid is empty")

    print("HNL Sensitivity Analysis")
    print(f"  Flavors: {flavors}")
    print(f"  Masses: {len(masses)} points "
          f"({min(masses):.2f} - {max(masses):.2f} GeV)")
    print(f"  Workers: {args.workers}")
    print(f"  Decay samples: {args.decay_samples}")
    if args.max_hit_events:
        print(f"  Hit-event cap: {args.max_hit_events} (weighted resampling)")
    if args.mass_stride > 1:
        print(f"  Mass stride: every {args.mass_stride} point(s), offset {args.mass_offset}")
    print(f"  Luminosity: {L_INT_PB:.0f} pb^-1 ({L_INT_PB/1e3:.0f} fb^-1)")
    print(f"  Threshold: N_signal >= {N_THRESHOLD}")
    print(f"  Inputs:    {LLP_VECTORS_DIR}")
    print(f"  Outputs:   {ANALYSIS_DIR}")

    n_processed = run(flavors, masses,
                      n_workers=args.workers,
                      force_geometry=args.force_geometry,
                      save_diagnostics=args.diagnostics,
                      decay_samples=args.decay_samples,
                      max_hit_events=args.max_hit_events,
                      checkpoint_every=args.checkpoint_every)
    if not n_processed:
        print("ERROR: analysis produced no results; see run_metadata.json "
              "for the per-point skip reasons.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
