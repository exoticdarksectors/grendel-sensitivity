"""SHiP BC10 curve computed with the corrected ALP widths, as sent by its author.

``arXiv-2501.04525/Sensitivity_ALP-fermion_at_SHiP-ECN3_Nev=2.3_Npot=6.e20.json``
is the SHiP sensitivity of arXiv:2501.04525 regenerated by M. Ovchynnikov with
the corrected ALP widths of SensCalc eb2c456 and exHad de535a6 (private
communication, 2026-10-16; cite arXiv:2501.04525). The file of 2026-10-11, with
the earlier widths, is kept beside it with the suffix ``_2026-10-12``.
It runs from below the eta to 4.76 GeV, unlike the published figure, which
shows only 0.6-2.0 GeV. The file holds nine variants (bremsstrahlung and
Drell-Yan descriptions); the author's choice is the central one. Each variant
is a list of closed domains in (m_a/GeV, g_Y = 2v/f_a), split at the eta and
eta' windows.

Output: ``curves/data/bc10/projections/ship_senscalc.dat``, rows
``mass_GeV  invf_GeV^-1`` (1/f BNT = g_Y / v_h).

    python -m curves.tools.senscalc_bc10_ship
"""
from __future__ import annotations

import json
import sys

from ..plot.data import BC10_DATA
from . import pdfio
from .sources import OZ_SHIP_SENSCALC_JSON, require

V_H = 246.0
DATE = "2026-10-19"
CENTRAL = {"Bremsstrahlung description": "AP-Central", "Drell-Yan description": "Central",
           "Decay description": "Default"}


def main() -> int:
    variants = json.loads(require(OZ_SHIP_SENSCALC_JSON).read_text())
    central = [v for v in variants if all(v[k] == val for k, val in CENTRAL.items())]
    if len(central) != 1:
        raise RuntimeError(f"expected one central variant, found {len(central)}")
    domains = central[0]["Sensitivity domains"]
    pdfio.write_chains(
        BC10_DATA / "projections" / "ship_senscalc.dat",
        [[(m, gy / V_H) for m, gy in dom] for dom in domains],
        ["SHiP fermiophilic-ALP (BC10) sensitivity, arXiv:2501.04525 regenerated with the corrected ALP widths",
         "(SensCalc eb2c456, exHad de535a6; M. Ovchynnikov, private communication 2026-10-16), central",
         "bremsstrahlung and Drell-Yan variant.",
         f"Date: {DATE}",
         "Source y axis g_Y = 2 v/f_a; stored as 1/f (BNT) = g_Y/246. Against the published figure",
         "(ship_alp2.dat): lower edge within 5 % at 0.6-1.8 GeV, 15 % lower at 2.0 GeV; upper edge",
         "within 16 % at 0.6-1.5 GeV, 30 % higher at 1.8 GeV."],
        columns='Format: chains separated by blank line; each row "mass_GeV  invf_GeV^-1"')
    return 0


if __name__ == "__main__":
    sys.exit(main())
